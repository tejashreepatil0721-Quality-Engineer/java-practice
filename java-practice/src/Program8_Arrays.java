public class Program8_Arrays {
    public static void main(String[] args){

        String flowerNames[] = {"Marigold", "Rose", "Lily", "Tulip", "Sunflower", "Lotus",
        "Jasmine", "Periwinkle", "Daisy", "Hibiscus"};

        System.out.println("Here are 10 flower names: ");
        for(int i=0; i < flowerNames.length; i++){
            System.out.println(flowerNames[i]);
        }
    }
}
