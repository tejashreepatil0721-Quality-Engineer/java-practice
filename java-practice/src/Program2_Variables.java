public class Program2_Variables {
    public static void main(String[] args){
        String name = "Tejashree Patil";
        int age = 27;
        double salary1 = 12.5;
        double salary2 = 14.5;
        char grade = 'A';
        boolean working = true;

        System.out.println("\nName: " + name);
        System.out.println("Age: "+ age);
        System.out.println("Expected Salary Range: " + salary1 + " to " + salary2);
        System.out.println("Grade: " + grade);
        System.out.println("Working: " + working);
    }
}
